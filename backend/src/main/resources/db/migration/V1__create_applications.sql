CREATE TABLE applications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company VARCHAR(120) NOT NULL CHECK (TRIM(company) <> ''),
 position VARCHAR(160) NOT NULL CHECK (TRIM(position) <> ''),
 url VARCHAR(1000) NOT NULL DEFAULT '',
 applied_on DATE NOT NULL,
 status VARCHAR(20) NOT NULL CHECK (status IN ('APPLIED','INTERVIEW','OFFER','REJECTED')),
 notes VARCHAR(3000) NOT NULL DEFAULT '',
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_applications_status_date ON applications(status,applied_on);
